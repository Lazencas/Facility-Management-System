package com.kgt.facility_access_management.access.domain;

import java.time.LocalDateTime;

public class AccessRequest {
    private Long id;
    private Long userId;
    private Long facilityId;
    private Long reviewedBy;
    private LocalDateTime reviewedAt;
    private String rejectReason;
    private AccessRequestStatus status;
    private String requestReason;
    private LocalDateTime accessStartAt;
    private LocalDateTime accessEndAt;
    private LocalDateTime createdAt;
    private LocalDateTime updatedAt;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getUserId() {
        return userId;
    }

    public void setUserId(Long userId) {
        this.userId = userId;
    }

    public Long getFacilityId() {
        return facilityId;
    }

    public void setFacilityId(Long facilityId) {
        this.facilityId = facilityId;
    }

    public Long getReviewedBy() {
        return reviewedBy;
    }

    public void setReviewedBy(Long reviewedBy) {
        this.reviewedBy = reviewedBy;
    }

    public LocalDateTime getReviewedAt() {
        return reviewedAt;
    }

    public void setReviewedAt(LocalDateTime reviewedAt) {
        this.reviewedAt = reviewedAt;
    }

    public String getRejectReason() {
        return rejectReason;
    }

    public void setRejectReason(String rejectReason) {
        this.rejectReason = rejectReason;
    }

    public AccessRequestStatus getStatus() {
        return status;
    }

    public void setStatus(AccessRequestStatus status) {
        this.status = status;
    }

    public String getRequestReason() {
        return requestReason;
    }

    public void setRequestReason(String requestReason) {
        this.requestReason = requestReason;
    }

    public LocalDateTime getAccessStartAt() {
        return accessStartAt;
    }

    public void setAccessStartAt(LocalDateTime accessStartAt) {
        this.accessStartAt = accessStartAt;
    }

    public LocalDateTime getAccessEndAt() {
        return accessEndAt;
    }

    public void setAccessEndAt(LocalDateTime accessEndAt) {
        this.accessEndAt = accessEndAt;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}
